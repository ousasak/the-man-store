<?php

namespace App\Http\Controllers\Api\V1\Storefront\Orders;

use App\Http\Controllers\Controller;
use App\Jobs\WatchKhqrPayment;
use App\Models\Order;
use App\Models\Payment;
use App\Services\InvoiceService;
use App\Services\OrderReceiptTokenService;
use App\Services\RielpayPaymentService;
use App\Support\BrandLogo;
use Barryvdh\DomPDF\Facade\Pdf;
use Endroid\QrCode\Color\Color;
use Endroid\QrCode\Encoding\Encoding;
use Endroid\QrCode\QrCode;
use Endroid\QrCode\Writer\PngWriter;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Response;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;

class PublicReceiptController extends Controller
{
    public function __construct(
        private readonly OrderReceiptTokenService $receiptTokens,
        private readonly InvoiceService $invoices,
        private readonly RielpayPaymentService $rielpayPayments,
    ) {
    }

    public function show(string $token): JsonResponse
    {
        $order = $this->receiptTokens->resolve($token);
        if (! $order) {
            return response()->json(['message' => 'Receipt link is invalid or expired.'], 404);
        }

        $invoice = $this->invoices->buildOrderInvoiceData(
            $order->loadMissing(['user', 'items.product', 'shipment']),
            InvoiceService::AUDIENCE_CUSTOMER
        );
        $invoice['brand_name'] = config('app.name', 'The Man Store');
        $invoice['logo_url'] = BrandLogo::url();
        $invoice['payment_method'] = $order->payment_method;
        $invoice['order_status'] = $order->status;
        $invoice['is_cod'] = $order->payment_method === 'cod';

        return response()->json([
            'message' => 'Receipt retrieved.',
            'data' => $invoice,
        ]);
    }

    public function downloadPdf(string $token): Response
    {
        $order = $this->receiptTokens->resolve($token);
        if (! $order) {
            return response('Receipt link is invalid or expired.', 404);
        }

        $invoice = $this->invoices->buildOrderInvoiceData(
            $order->loadMissing(['user', 'items.product', 'shipment']),
            InvoiceService::AUDIENCE_CUSTOMER
        );
        $invoice['logo_url'] = BrandLogo::invoiceLogoUrl();

        $pdf = Pdf::loadView('invoices.bulk', [
            'invoices' => [$invoice],
            'isBulk' => false,
            'brandName' => config('app.name', 'The Man Store'),
            'logoUrl' => BrandLogo::invoiceLogoUrl(),
        ])
            ->setOptions([
                'isRemoteEnabled' => true,
                'isHtml5ParserEnabled' => true,
                'defaultFont' => 'DejaVu Sans',
            ])
            ->setPaper('A4', 'portrait');

        $filename = 'invoice-'.($invoice['order_number'] ?: $order->id).'.pdf';

        return response($pdf->output(), 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'attachment; filename="'.$filename.'"',
        ]);
    }

    public function paymentQr(string $token): JsonResponse
    {
        $order = $this->receiptTokens->resolve($token);
        if (! $order) {
            return response()->json(['message' => 'Receipt link is invalid or expired.'], 404);
        }

        if ($order->payment_status === 'paid') {
            return response()->json(['message' => 'This order is already paid.'], 409);
        }

        try {
            if ($order->payment_method === 'cod') {
                return response()->json([
                    'message' => 'Shop KHQR is only generated by the driver or admin. Pay the driver when your order is delivered.',
                ], 422);
            } elseif ($order->payment_method === 'bakong_khqr') {
                $payment = $this->resolveOnlineKhqr($order);
            } else {
                return response()->json(['message' => 'Online payment is not available for this order.'], 422);
            }

            return response()->json([
                'message' => 'Payment QR ready.',
                'data' => [
                    'qr_string' => $payment['qr_string'] ?? null,
                    'amount' => $payment['amount'] ?? null,
                    'currency' => $payment['currency'] ?? 'KHR',
                    'status' => $payment['status'] ?? 'pending',
                    'payment_method' => $order->payment_method,
                    'is_cod' => $order->payment_method === 'cod',
                ],
            ]);
        } catch (\Throwable $e) {
            Log::error('Public receipt payment QR failed', [
                'order_id' => $order->id,
                'error' => $e->getMessage(),
            ]);

            return response()->json([
                'message' => $e->getMessage() ?: 'Failed to generate payment QR.',
            ], 500);
        }
    }

    /**
     * @return array<string, mixed>
     */
    private function resolveOnlineKhqr(Order $order): array
    {
        $existing = Payment::where('order_id', $order->id)
            ->khqrProvider()
            ->where('status', 'pending')
            ->where(function ($query) {
                $query->whereNull('expires_at')->orWhere('expires_at', '>', now());
            })
            ->latest('id')
            ->first();

        if ($existing && $existing->qr_string) {
            WatchKhqrPayment::dispatch((int) $existing->id);
            $this->rielpayPayments->scheduleAutoConfirm($existing, $order);

            return [
                'qr_string' => $existing->qr_string,
                'amount' => $existing->amount,
                'currency' => $existing->currency,
                'status' => $existing->status,
            ];
        }

        return DB::transaction(function () use ($order, $existing) {
            Payment::where('order_id', $order->id)
                ->khqrProvider()
                ->where('status', 'pending')
                ->whereNotNull('expires_at')
                ->where('expires_at', '<=', now())
                ->update(['status' => 'expired']);

            $payment = $existing ?: Payment::create([
                'order_id' => $order->id,
                'provider' => 'rielpay',
                'amount' => $order->total,
                'currency' => config('services.rielpay.currency', 'KHR'),
                'method' => 'bakong_khqr',
                'status' => 'pending',
            ]);

            $result = $this->rielpayPayments->generate($order, $payment);
            $payment->update([
                'provider' => 'rielpay',
                'bill_number' => $result['bill_number'],
                'md5' => $result['md5'],
                'khqr_payload' => $result['payload'],
                'qr_string' => $result['qr_string'],
                'expires_at' => $result['expires_at'],
                'raw_response' => $result['payload'],
            ]);

            $fresh = $payment->fresh();
            WatchKhqrPayment::dispatch((int) $fresh->id);
            $this->rielpayPayments->scheduleAutoConfirm($fresh, $order);

            return [
                'qr_string' => $fresh->qr_string,
                'amount' => $fresh->amount,
                'currency' => $fresh->currency,
                'status' => $fresh->status,
            ];
        });
    }

    private function buildQrDataUri(?string $payload): ?string
    {
        if (empty($payload)) {
            return null;
        }

        $writer = new PngWriter();
        $qrCode = QrCode::create($payload)
            ->setEncoding(new Encoding('UTF-8'))
            ->setSize(260)
            ->setMargin(10)
            ->setForegroundColor(new Color(0, 0, 0))
            ->setBackgroundColor(new Color(255, 255, 255));

        $result = $writer->write($qrCode);

        return 'data:'.$result->getMimeType().';base64,'.base64_encode($result->getString());
    }
}
